#!/usr/bin/env python3
"""List PR commits with a co-author trailer or AI authorship.

Usage: $TOOLS/skills/pr-review/scripts/check_commit_trailers.py [base-ref] [--pr N]
  base-ref defaults to origin/main (merge-base with HEAD is used). Run it
  inside the PR worktree. --pr N also checks, through `gh api`, that every
  commit's GitHub author is the PR's author.

Team policy: no `Co-authored-by:` trailer of any kind, and no commit authored,
committed or generated by an AI tool. Trailers live in the commit body, so
checking subjects (the Conventional Commits validator) never sees them.

  COAUTHOR  a `Co-authored-by:` trailer (any co-author, bots included)
  AI-TRAIL  a `Generated-by:`/`Assisted-by:`/`Signed-off-by:` trailer, or a
            body line, naming an AI tool ("Generated with Claude Code", …)
  AI-AUTHOR the author or committer name or email matches an AI tool
  NOT-PR-AUTHOR (with --pr) the commit's GitHub author isn't the PR's author

Every hit is Important and blocks merge: each commit must come from the human
who opened the PR.
Report all hits as one PR-level Important finding listing SHA + subject per commit.
Exit status 1 when anything is reported.
"""
import re
import subprocess
import sys

AI_RE = re.compile(r"\b(claude|anthropic|copilot|cursor|chatgpt|openai|gpt-?\d|gemini|codex|devin)\b", re.I)
COAUTHOR_RE = re.compile(r"^\s*co-authored-by:", re.I)
AI_TRAILER_RE = re.compile(r"^\s*(generated-by|assisted-by|signed-off-by):", re.I)
GENERATED_RE = re.compile(r"generated (with|by)", re.I)
SEP = "\x1e"


def sh(*cmd):
    return subprocess.run(cmd, capture_output=True, text=True, check=True).stdout


def pr_author_hits(pr, repo="ballerina-nutcracker/ballerina"):
    """Commits on PR pr whose GitHub author isn't the PR's author."""
    owner = sh("gh", "api", f"repos/{repo}/pulls/{pr}", "-q", ".user.login").strip()
    rows = sh("gh", "api", "--paginate", f"repos/{repo}/pulls/{pr}/commits",
              "-q", '.[] | [.sha[0:9], (.author.login // "?"), (.commit.message|split("\n")[0])] | @tsv')
    hits = []
    for row in rows.splitlines():
        sha, login, subject = row.split("\t", 2)
        if login != owner:
            hits.append(f"NOT-PR-AUTHOR {sha} {subject}\n          author {login}, PR opened by {owner}")
    return hits


def main():
    args = sys.argv[1:]
    pr = None
    if "--pr" in args:
        at = args.index("--pr")
        pr = args[at + 1]
        del args[at:at + 2]
    base = args[0] if args else "origin/main"
    try:
        merge_base = sh("git", "merge-base", base, "HEAD").strip()
    except subprocess.CalledProcessError:
        sys.exit(f"check_commit_trailers: no merge-base with {base}; run it inside the PR worktree")
    log = sh("git", "log", "--no-merges", f"--format=%h%x1f%an <%ae>%x1f%cn <%ce>%x1f%s%x1f%b{SEP}", f"{merge_base}..HEAD")
    hits = []
    for record in log.split(SEP):
        if not record.strip():
            continue
        sha, author, committer, subject, body = record.strip("\n").split("\x1f", 4)
        tags = []
        for line in body.split("\n"):
            if COAUTHOR_RE.match(line):
                tags.append(("COAUTHOR", line.strip()))
            elif AI_TRAILER_RE.match(line) and AI_RE.search(line):
                tags.append(("AI-TRAIL", line.strip()))
            elif GENERATED_RE.search(line) and AI_RE.search(line):
                tags.append(("AI-TRAIL", line.strip()))
        for who in (author, committer):
            if AI_RE.search(who):
                tags.append(("AI-AUTHOR", who))
        for tag, detail in tags:
            hits.append(f"{tag:<9} {sha} {subject}\n          {detail}")
    if pr:
        hits += pr_author_hits(pr)
    if not hits:
        return 0
    print("\n".join(hits))
    return 1


if __name__ == "__main__":
    sys.exit(main())
