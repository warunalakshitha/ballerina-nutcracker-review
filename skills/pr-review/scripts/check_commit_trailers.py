#!/usr/bin/env python3
"""List PR commits with a co-author trailer or AI authorship.

Usage: $TOOLS/skills/pr-review/scripts/check_commit_trailers.py [base-ref] [--pr N]
         [--repo OWNER/NAME] [--conventional] [--ai-only]
  base-ref defaults to origin/main (merge-base with HEAD is used). Run it
  inside the PR worktree. --pr N also checks, through `gh api`, that every
  commit's GitHub author is the PR's author. --repo names the PR's repo
  (default ballerina-nutcracker/ballerina). --conventional also validates
  every commit subject (and, with --pr, the PR title) with the nutcracker
  `validate_commits.py`, for repos whose CI doesn't (the playground).
  --ai-only allows other human authors and human co-authors (the playground,
  where e.g. a release-sync PR carries teammates' commits) and reports only
  AI tools: NOT-PR-AUTHOR becomes AI-LOGIN, and COAUTHOR needs an AI name.

Team policy: no `Co-authored-by:` trailer of any kind, and no commit authored,
committed or generated by an AI tool. Trailers live in the commit body, so
checking subjects (the Conventional Commits validator) never sees them.

  COAUTHOR  a `Co-authored-by:` trailer (any co-author, bots included)
  AI-TRAIL  a `Generated-by:`/`Assisted-by:`/`Signed-off-by:` trailer, or a
            body line, naming an AI tool ("Generated with Claude Code", …)
  AI-AUTHOR the author or committer name or email matches an AI tool
  NOT-PR-AUTHOR (with --pr) the commit's GitHub author isn't the PR's author
  AI-LOGIN  (with --pr --ai-only) the commit's GitHub author is an AI tool or bot
  PR-BODY   (with --pr) the PR description carries an AI attribution line
            ("🤖 Generated with [Claude Code]", "Co-authored-by: Copilot", …)
  SUBJECT   (with --conventional) a commit subject fails Conventional Commits,
            or is a leftover `fixup!` / `squash!`
  PR-TITLE  (with --conventional and --pr) the PR title fails it

Every authorship hit is Important and blocks merge: each commit must come from
the human who opened the PR.
Report all hits as one PR-level Important finding listing SHA + subject per commit.
Exit status 1 when anything is reported.
"""
import base64
import re
import subprocess
import sys

AI_RE = re.compile(r"\b(claude|anthropic|copilot|cursor|chatgpt|openai|gpt-?\d|gemini|codex|devin)\b", re.I)
COAUTHOR_RE = re.compile(r"^\s*co-authored-by:", re.I)
AI_TRAILER_RE = re.compile(r"^\s*(generated-by|assisted-by|signed-off-by):", re.I)
GENERATED_RE = re.compile(r"generated (with|by)", re.I)
SEP = "\x1e"
DEFAULT_REPO = "ballerina-nutcracker/ballerina"
VALIDATOR = "repos/ballerina-nutcracker/ballerina/contents/.github/scripts/validate_commits.py"


def sh(*cmd):
    return subprocess.run(cmd, capture_output=True, text=True, check=True).stdout


def pr_author_hits(pr, repo=DEFAULT_REPO, ai_only=False):
    """Commits on PR pr whose GitHub author isn't the PR's author (or, with
    ai_only, is an AI tool or bot account)."""
    owner = sh("gh", "api", f"repos/{repo}/pulls/{pr}", "-q", ".user.login").strip()
    rows = sh("gh", "api", "--paginate", f"repos/{repo}/pulls/{pr}/commits",
              "-q", '.[] | [.sha[0:9], (.author.login // "?"), (.commit.message|split("\n")[0])] | @tsv')
    hits = []
    for row in rows.splitlines():
        sha, login, subject = row.split("\t", 2)
        if ai_only:
            if AI_RE.search(login) or login.endswith("[bot]"):
                hits.append(f"AI-LOGIN  {sha} {subject}\n          author {login}")
        elif login != owner:
            hits.append(f"NOT-PR-AUTHOR {sha} {subject}\n          author {login}, PR opened by {owner}")
    return hits


def pr_body_hits(pr, repo=DEFAULT_REPO):
    """AI attribution lines in the PR description."""
    body = sh("gh", "api", f"repos/{repo}/pulls/{pr}", "-q", ".body") or ""
    hits = []
    for line in body.splitlines():
        if (GENERATED_RE.search(line) or COAUTHOR_RE.match(line) or AI_TRAILER_RE.match(line)) and AI_RE.search(line):
            hits.append(f"PR-BODY   #{pr} description\n          {line.strip()[:120]}")
    return hits


def load_validator():
    """validation_errors() from nutcracker's validate_commits.py on main."""
    source = base64.b64decode(sh("gh", "api", VALIDATOR, "-q", ".content")).decode()
    scope = {"__name__": "validate_commits"}
    exec(compile(source, "validate_commits.py", "exec"), scope)
    return scope["validation_errors"]


def subject_errors(validate, subject):
    errors = list(validate(subject))
    if re.match(r"^(fixup|squash|amend)! ", subject):
        errors.append("is an unsquashed fixup/squash commit")
    return errors


def pop_flag(args, name, has_value=True):
    if name not in args:
        return None
    at = args.index(name)
    if not has_value:
        del args[at]
        return True
    value = args[at + 1]
    del args[at:at + 2]
    return value


def main():
    args = sys.argv[1:]
    pr = pop_flag(args, "--pr")
    repo = pop_flag(args, "--repo") or DEFAULT_REPO
    validate = load_validator() if pop_flag(args, "--conventional", False) else None
    ai_only = bool(pop_flag(args, "--ai-only", False))
    base = args[0] if args else "origin/main"
    try:
        merge_base = sh("git", "merge-base", base, "HEAD").strip()
    except subprocess.CalledProcessError:
        sys.exit(f"check_commit_trailers: no merge-base with {base}; run it inside the PR worktree")
    log = sh("git", "log", "--no-merges", f"--format=%h%x1f%an <%ae>%x1f%cn <%ce>%x1f%s%x1f%b{SEP}", f"{merge_base}..HEAD")
    hits = []
    for record in log.split(SEP):
        if not record.strip():
            continue
        sha, author, committer, subject, body = record.strip("\n").split("\x1f", 4)
        tags = []
        for line in body.split("\n"):
            if COAUTHOR_RE.match(line) and (not ai_only or AI_RE.search(line)):
                tags.append(("COAUTHOR", line.strip()))
            elif AI_TRAILER_RE.match(line) and AI_RE.search(line):
                tags.append(("AI-TRAIL", line.strip()))
            elif GENERATED_RE.search(line) and AI_RE.search(line):
                tags.append(("AI-TRAIL", line.strip()))
        for who in (author, committer):
            if AI_RE.search(who):
                tags.append(("AI-AUTHOR", who))
        if validate:
            for err in subject_errors(validate, subject):
                tags.append(("SUBJECT", err))
        for tag, detail in tags:
            hits.append(f"{tag:<9} {sha} {subject}\n          {detail}")
    if pr:
        hits += pr_author_hits(pr, repo, ai_only)
        hits += pr_body_hits(pr, repo)
        if validate:
            title = sh("gh", "api", f"repos/{repo}/pulls/{pr}", "-q", ".title").strip()
            for err in subject_errors(validate, title):
                hits.append(f"PR-TITLE  #{pr} {title}\n          {err}")
    if not hits:
        return 0
    print("\n".join(hits))
    return 1


if __name__ == "__main__":
    sys.exit(main())
